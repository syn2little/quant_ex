@dataclass
class StrategyFeedback:
    """Feedback object generated after an agent plan has measurable outcomes."""

    run_id: str
    generated_at: str
    result: MetricSnapshot
    control: Optional[MetricSnapshot] = None
    deltas: Dict[str, float] = field(default_factory=dict)
    observations: List[str] = field(default_factory=list)
    hypothesis_evaluation: str = "inconclusive"
    decision: str = "hold"
    new_hypothesis: str = ""
    next_ablation: str = ""
    do_not_repeat: List[str] = field(default_factory=list)
    reflection: str = ""

    def to_dict(self) -> Dict[str, Any]:
        payload = asdict(self)
        payload["result"] = self.result.to_dict()
        payload["control"] = self.control.to_dict() if self.control else None
        return payload

    def to_markdown(self) -> str:
        lines = [
            f"# Agent Strategy Feedback: {self.run_id}",
            "",
            f"- Generated: {self.generated_at}",
            f"- Decision: {self.decision}",
            f"- Hypothesis evaluation: {self.hypothesis_evaluation}",
            "",
            "## Result",
            f"- Source: `{self.result.source_path}`",
            f"- Kind: {self.result.result_kind}",
            f"- Rank metric: {self.result.rank_metric}",
            f"- Best row: `{self.result.best_row}`",
        ]
        if self.control:
            lines.extend(
                [
                    "",
                    "## Control",
                    f"- Source: `{self.control.source_path}`",
                    f"- Kind: {self.control.result_kind}",
                    f"- Rank metric: {self.control.rank_metric}",
                    f"- Best row: `{self.control.best_row}`",
                ]
            )
        lines.extend(["", "## Deltas", *[f"- {key}: {value:.6f}" for key, value in self.deltas.items()]])
        lines.extend(["", "## Observations", *[f"- {item}" for item in self.observations]])
        lines.extend(
            [
                "",
                "## Reflection",
                self.reflection,
                "",
                "## Next",
                f"- New hypothesis: {self.new_hypothesis}",
                f"- Next ablation: {self.next_ablation}",
                *[f"- Do not repeat: {item}" for item in self.do_not_repeat],
            ]
        )
        return "\n".join(lines) + "\n"
