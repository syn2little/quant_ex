@dataclass
class StrategyIterationPlan:
    """Final artifact of a multi-role strategy iteration planning run."""

    run_id: str
    objective: str
    generated_at: str
    role_reports: List[RoleReport]
    experiment_arms: List[ExperimentArm]
    validation_ladder: List[str]
    decision_gates: List[str]
    synthesis: str
    next_actions: List[str] = field(default_factory=list)
    discussion_decisions: List[ChairDecision] = field(default_factory=list)
    research_constraints: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        payload = asdict(self)
        payload["role_reports"] = [r.to_dict() for r in self.role_reports]
        payload["experiment_arms"] = [a.to_dict() for a in self.experiment_arms]
        payload["discussion_decisions"] = [d.to_dict() for d in self.discussion_decisions]
        return payload

    def to_markdown(self) -> str:
        lines = [
            f"# Agent Strategy Iteration Plan: {self.run_id}",
            "",
            f"- Generated: {self.generated_at}",
            f"- Objective: {self.objective}",
            "",
            "## Synthesis",
            self.synthesis,
            "",
            "## Role Reports",
        ]
        if self.discussion_decisions:
            lines.extend(["", "## Discussion Chair Decisions"])
            for decision in self.discussion_decisions:
                target = ", ".join(decision.next_roles) or decision.next_role or "final"
                lines.extend(
                    [
                        "",
                        f"### Turn {decision.turn_index}: {decision.action} -> {target}",
                        f"- Decision: {decision.decision}",
                        f"- Confidence: {decision.confidence:.2f}",
                        f"- Focus: {decision.focus or 'none'}",
                        f"- Rationale: {decision.rationale or 'none'}",
                    ]
                )
                if decision.final_summary:
                    lines.append(f"- Final summary: {decision.final_summary}")
                if decision.missing_requirements:
                    lines.append(f"- Missing requirements: {', '.join(decision.missing_requirements)}")
                if decision.blocked_reason:
                    lines.append(f"- Blocked reason: {decision.blocked_reason}")
        if self.research_constraints:
            metric_policy = self.research_constraints.get("metric_policy") or {}
            lines.extend(
                [
                    "",
                    "## Research Constraints",
                    f"- Default controls: {', '.join(self.research_constraints.get('default_controls') or []) or 'none'}",
                    f"- Rank metric: {metric_policy.get('rank_metric') or 'none'}",
                    f"- Promotion evidence: {metric_policy.get('promotion_evidence') or 'none'}",
                    "- Known traps:",
                    *[f"  - {item}" for item in self.research_constraints.get("known_traps") or []],
                    "- Required plan fields:",
                    *[f"  - {item}" for item in self.research_constraints.get("required_plan_fields") or []],
                ]
            )
        for report in self.role_reports:
            lines.extend(
                [
                    "",
                    f"### {report.role}",
                    report.thesis,
                    "",
                    "Evidence:",
                    *[f"- {item}" for item in report.evidence],
                    "Proposals:",
                    *[f"- {item}" for item in report.proposals],
                    "Risks:",
                    *[f"- {item}" for item in report.risks],
                    f"Verdict: {report.verdict} | Confidence: {report.confidence:.2f}",
                ]
            )
        lines.extend(["", "## Experiment Arms"])
        for arm in self.experiment_arms:
            lines.extend(
                [
                    "",
                    f"### {arm.arm_id}",
                    f"- Type: {arm.change_type}",
                    f"- Owner role: {arm.owner_role}",
                    f"- Hypothesis: {arm.hypothesis}",
                    f"- Requires approval: {arm.requires_approval}",
                    "- Validation:",
                    *[f"  - `{cmd}`" for cmd in arm.validation_commands],
                    "- Success criteria:",
                    *[f"  - {criterion}" for criterion in arm.success_criteria],
                    "- Risks:",
                    *[f"  - {risk}" for risk in arm.risk_notes],
                ]
            )
        lines.extend(["", "## Validation Ladder", *[f"- {item}" for item in self.validation_ladder]])
        lines.extend(["", "## Decision Gates", *[f"- {item}" for item in self.decision_gates]])
        lines.extend(["", "## Next Actions", *[f"- {item}" for item in self.next_actions]])
        return "\n".join(lines) + "\n"


