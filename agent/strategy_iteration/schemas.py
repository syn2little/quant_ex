@dataclass
class ChairDecision:
    """Virtual meeting chair decision for adaptive role participation."""

    turn_index: int
    action: str = "call_role"
    next_role: str = ""
    next_roles: List[str] = field(default_factory=list)
    rationale: str = ""
    focus: str = ""
    decision: str = "continue"
    final_summary: str = ""
    confidence: float = 0.5
    coverage: Dict[str, bool] = field(default_factory=dict)
    missing_requirements: List[str] = field(default_factory=list)
    blocked_reason: str = ""

    @classmethod
    def from_dict(cls, turn_index: int, payload: Dict[str, Any]) -> "ChairDecision":
        next_roles = _clean_list(payload.get("next_roles"))
        if not next_roles:
            next_role = str(payload.get("next_role") or payload.get("role") or "")
            next_roles = [next_role] if next_role else []
        return cls(
            turn_index=turn_index,
            action=str(payload.get("action") or "call_role"),
            next_role=next_roles[0] if next_roles else "",
            next_roles=next_roles,
            rationale=str(payload.get("rationale") or payload.get("why") or ""),
            focus=str(payload.get("focus") or payload.get("question") or ""),
            decision=str(payload.get("decision") or "continue"),
            final_summary=str(payload.get("final_summary") or payload.get("summary") or ""),
            confidence=float(payload.get("confidence") or 0.5),
            coverage=dict(payload.get("coverage") or {}),
            missing_requirements=_clean_list(payload.get("missing_requirements")),
            blocked_reason=str(payload.get("blocked_reason") or ""),
        )

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


