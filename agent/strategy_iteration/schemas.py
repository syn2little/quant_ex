@dataclass
class CommandExecutionPlan:
    """Auditable command plan produced from an agent strategy plan."""

    run_id: str
    generated_at: str
    policy: str
    commands: List[CommandProposal] = field(default_factory=list)
    results: List[CommandExecutionResult] = field(default_factory=list)
    feedback_candidates: List[FeedbackCandidate] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "run_id": self.run_id,
            "generated_at": self.generated_at,
            "policy": self.policy,
            "commands": [item.to_dict() for item in self.commands],
            "results": [item.to_dict() for item in self.results],
            "feedback_candidates": [item.to_dict() for item in self.feedback_candidates],
        }

    def to_markdown(self) -> str:
        lines = [
            f"# Agent Command Plan: {self.run_id}",
            "",
            f"- Generated: {self.generated_at}",
            f"- Policy: {self.policy}",
            "",
            "## Commands",
        ]
        for item in self.commands:
            lines.extend(
                [
                    "",
                    f"### {item.command_id}",
                    f"- Source: {item.source}",
                    f"- Purpose: {item.purpose}",
                    f"- Risk tags: {', '.join(item.risk_tags) or 'none'}",
                    f"- Requires approval: {item.requires_approval}",
                    f"- Approval reason: {item.approval_reason or 'none'}",
                    f"- Timeout seconds: {item.timeout_seconds}",
                    f"- Command SHA256: `{item.command_sha256}`",
                    f"- Command: `{item.command}`",
                ]
            )
        if self.results:
            lines.extend(["", "## Results"])
            for result in self.results:
                status = "skipped" if result.skipped else f"returncode={result.returncode}"
                lines.extend(
                    [
                        "",
                        f"### {result.command_id}",
                        f"- Status: {status}",
                        f"- Skip reason: {result.skip_reason or 'none'}",
                        f"- Approval reason: {result.approval_reason or 'none'}",
                    ]
                )
        if self.feedback_candidates:
            lines.extend(["", "## Feedback Candidates"])
            for candidate in self.feedback_candidates:
                lines.extend(
                    [
                        "",
                        f"### {candidate.command_id}",
                        f"- Kind: {candidate.result_kind}",
                        f"- Ready: {candidate.ready}",
                        f"- Result CSV: `{candidate.result_csv}`",
                        f"- Reason: {candidate.reason or 'none'}",
                        f"- Feedback command: `{candidate.feedback_command}`",
                    ]
                )
        return "\n".join(lines) + "\n"


